//! Emit a machine-readable TOML report from a solved layout.

use crate::config::Anchor;
use crate::tree::SolvedLayout;
use std::fmt::Write;

/// Generate a TOML report for AI-friendly iteration.
pub fn emit_report(layout: &SolvedLayout) -> String {
    let mut out = String::new();

    writeln!(out, "# Auto-generated by FigureFit").unwrap();
    writeln!(out, "name = {:?}", layout.figure_name).unwrap();
    writeln!(out, "score = {:.4}", layout.cost).unwrap();
    writeln!(out, "solver_mode = {:?}", layout.solver_mode).unwrap();
    writeln!(out, "page_width_mm = {:.1}", layout.page_width_mm).unwrap();
    writeln!(out, "height_mm = {:.1}", layout.height_mm).unwrap();
    writeln!(out, "max_height_mm = {:.1}", layout.page_max_height_mm).unwrap();
    writeln!(
        out,
        "height_utilization = {:.3}",
        layout.height_mm / layout.page_max_height_mm
    )
    .unwrap();
    writeln!(out).unwrap();

    writeln!(out, "[score_components]").unwrap();
    writeln!(out, "aspect = {:.6}", layout.score.aspect).unwrap();
    writeln!(out, "void = {:.6}", layout.score.void).unwrap();
    writeln!(out, "dimension = {:.6}", layout.score.dimension).unwrap();
    writeln!(out, "constraint = {:.6}", layout.score.constraint).unwrap();
    writeln!(
        out,
        "optional_content = {:.6}",
        layout.score.optional_content
    )
    .unwrap();
    writeln!(
        out,
        "required_content = {:.6}",
        layout.score.required_content
    )
    .unwrap();
    writeln!(
        out,
        "height_utilization = {:.6}",
        layout.score.height_utilization
    )
    .unwrap();
    writeln!(out).unwrap();

    writeln!(out, "[checks]").unwrap();
    writeln!(out, "passed = {}", layout.checks.passed).unwrap();
    write!(out, "issues = [").unwrap();
    for (i, issue) in layout.checks.issues.iter().enumerate() {
        if i > 0 {
            write!(out, ", ").unwrap();
        }
        write!(out, "{issue:?}").unwrap();
    }
    writeln!(out, "]").unwrap();
    writeln!(out).unwrap();

    for p in &layout.placements {
        writeln!(out, "[[placed]]").unwrap();
        writeln!(out, "id = {:?}", p.panel_id).unwrap();
        writeln!(out, "group = {:?}", p.group_id).unwrap();
        writeln!(out, "x_frac = {:.4}", p.rect.x).unwrap();
        writeln!(out, "y_frac = {:.4}", p.rect.y).unwrap();
        writeln!(out, "w_frac = {:.4}", p.rect.w).unwrap();
        writeln!(out, "h_frac = {:.4}", p.rect.h).unwrap();
        writeln!(out, "w_mm = {:.1}", p.w_mm).unwrap();
        writeln!(out, "h_mm = {:.1}", p.h_mm).unwrap();
        writeln!(out, "aspect_actual = {:.3}", p.aspect_actual).unwrap();
        writeln!(out, "aspect_target = {:.3}", p.aspect_target).unwrap();
        match &p.alt_chosen {
            Some(alt) => writeln!(out, "alt_chosen = {alt:?}").unwrap(),
            None => writeln!(out, "alt_chosen = \"primary\"").unwrap(),
        }
        if p.pad_mm > 0.0 {
            writeln!(out, "pad_mm = {:.1}", p.pad_mm).unwrap();
        }
        if let Some(label_gutter) = p.label_gutter_mm {
            writeln!(out, "label_gutter_mm = {label_gutter:.1}").unwrap();
        }
        if let Some(legend_margin) = p.legend_margin_mm {
            writeln!(out, "legend_margin_mm = {legend_margin:.1}").unwrap();
        }
        if p.void_frac > 1e-6 {
            writeln!(out, "void_frac = {:.3}", p.void_frac).unwrap();
            writeln!(out, "void_side = \"{}\"", p.void_side).unwrap();
        }
        writeln!(out).unwrap();
    }

    for ip in &layout.inset_placements {
        writeln!(out, "[[inset]]").unwrap();
        writeln!(out, "id = {:?}", ip.panel_id).unwrap();
        writeln!(out, "host = {:?}", ip.host_id).unwrap();
        writeln!(out, "group = {:?}", ip.group_id).unwrap();
        writeln!(out, "anchor = {:?}", anchor_name(ip.anchor)).unwrap();
        writeln!(out, "x_frac = {:.4}", ip.rect.x).unwrap();
        writeln!(out, "y_frac = {:.4}", ip.rect.y).unwrap();
        writeln!(out, "w_frac = {:.4}", ip.rect.w).unwrap();
        writeln!(out, "h_frac = {:.4}", ip.rect.h).unwrap();
        writeln!(out, "w_mm = {:.1}", ip.w_mm).unwrap();
        writeln!(out, "h_mm = {:.1}", ip.h_mm).unwrap();
        writeln!(out, "aspect_actual = {:.3}", ip.aspect_actual).unwrap();
        writeln!(out, "aspect_target = {:.3}", ip.aspect_target).unwrap();
        match &ip.alt_chosen {
            Some(alt) => writeln!(out, "alt_chosen = {alt:?}").unwrap(),
            None => writeln!(out, "alt_chosen = \"primary\"").unwrap(),
        }
        if ip.pad_mm > 0.0 {
            writeln!(out, "pad_mm = {:.1}", ip.pad_mm).unwrap();
        }
        if let Some(label_gutter) = ip.label_gutter_mm {
            writeln!(out, "label_gutter_mm = {label_gutter:.1}").unwrap();
        }
        if let Some(legend_margin) = ip.legend_margin_mm {
            writeln!(out, "legend_margin_mm = {legend_margin:.1}").unwrap();
        }
        if ip.void_frac > 1e-6 {
            writeln!(out, "void_frac = {:.3}", ip.void_frac).unwrap();
            writeln!(out, "void_side = \"{}\"", ip.void_side).unwrap();
        }
        writeln!(out).unwrap();
    }

    for d in &layout.dropped_groups {
        writeln!(out, "[[dropped]]").unwrap();
        writeln!(out, "group = {:?}", d.group_id).unwrap();
        writeln!(out, "priority = {}", d.priority).unwrap();
        writeln!(out, "reason = {:?}", d.reason).unwrap();
        write!(out, "panels = [").unwrap();
        for (i, pid) in d.panel_ids.iter().enumerate() {
            if i > 0 {
                write!(out, ", ").unwrap();
            }
            write!(out, "{pid:?}").unwrap();
        }
        writeln!(out, "]").unwrap();
        writeln!(out).unwrap();
    }

    for v in &layout.constraint_violations {
        writeln!(out, "[[constraint_violation]]").unwrap();
        writeln!(out, "kind = {:?}", v.kind).unwrap();
        writeln!(out, "hard = {}", v.hard).unwrap();
        writeln!(out, "weight = {:.3}", v.weight).unwrap();
        writeln!(out, "penalty = {:.6}", v.penalty).unwrap();
        write!(out, "ids = [").unwrap();
        for (i, id) in v.ids.iter().enumerate() {
            if i > 0 {
                write!(out, ", ").unwrap();
            }
            write!(out, "{id:?}").unwrap();
        }
        writeln!(out, "]").unwrap();
        writeln!(out).unwrap();
    }

    for c in &layout.candidate_summaries {
        writeln!(out, "[[candidate]]").unwrap();
        writeln!(out, "rank = {}", c.rank).unwrap();
        writeln!(out, "cost = {:.6}", c.cost).unwrap();
        writeln!(out, "height_mm = {:.1}", c.height_mm).unwrap();
        writeln!(out, "panels = {}", c.panels).unwrap();
        if let Some(reason) = &c.rejected_reason {
            writeln!(out, "rejected_reason = {reason:?}").unwrap();
        }
        write!(out, "dropped_groups = [").unwrap();
        for (i, id) in c.dropped_groups.iter().enumerate() {
            if i > 0 {
                write!(out, ", ").unwrap();
            }
            write!(out, "{id:?}").unwrap();
        }
        writeln!(out, "]").unwrap();
        writeln!(out).unwrap();
    }

    out
}

fn anchor_name(anchor: Anchor) -> &'static str {
    match anchor {
        Anchor::TopLeft => "top-left",
        Anchor::TopRight => "top-right",
        Anchor::BottomLeft => "bottom-left",
        Anchor::BottomRight => "bottom-right",
    }
}
