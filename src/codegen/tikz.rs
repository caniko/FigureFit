//! Emit a TikZ figure environment from a solved layout.
//!
//! Panels are shrunk slightly from their solver-computed rects to
//! insert visual gaps (panel_gap_mm within groups, group_gap_mm
//! between groups).

use crate::config::PageConfig;
use crate::tree::SolvedLayout;
use std::fmt::Write;

/// Generate a LaTeX TikZ figure from the solved layout.
///
/// Each panel is clipped to its solver-computed bounding box and the
/// `\includesvg` call specifies **both** width and height.  This ensures
/// that an SVG whose intrinsic aspect differs from the solver's allocation
/// cannot overflow its rectangle — LaTeX scales the SVG to fit within the
/// smaller constraint while preserving aspect ratio.
pub fn emit_tikz(layout: &SolvedLayout, page: &PageConfig) -> String {
    let mut out = String::new();
    let height_ratio = layout.height_mm / layout.page_width_mm;

    // Gap as fraction of figure dimensions.
    let gap_w = page.panel_gap_mm / page.width_mm;
    let gap_h = page.panel_gap_mm / layout.height_mm;

    // Half-gap: each panel is inset by half the gap on each side.
    let hgw = gap_w / 2.0;
    let hgh = gap_h / 2.0;

    // Label gutter: fraction of figure height reserved at the top of each panel.
    let label_h = page.label_height_mm / layout.height_mm;

    writeln!(out, "% Auto-generated by FigureFit - do not edit").unwrap();
    writeln!(out, "% Source: {}.toml", layout.figure_name).unwrap();
    writeln!(
        out,
        "% Score: {:.3} | Height: {:.1}mm / {:.1}mm ({:.0}% utilization)",
        layout.cost,
        layout.height_mm,
        layout.page_max_height_mm,
        layout.height_mm / layout.page_max_height_mm * 100.0
    )
    .unwrap();
    writeln!(
        out,
        "% Gaps: {:.1}mm panel, {:.1}mm group",
        page.panel_gap_mm, page.group_gap_mm
    )
    .unwrap();
    writeln!(
        out,
        "\\ifdefined\\fw\\else\\newdimen\\fw\\fi \\fw=\\linewidth"
    )
    .unwrap();
    writeln!(
        out,
        "\\ifdefined\\fh\\else\\newdimen\\fh\\fi \\fh={height_ratio:.4}\\linewidth",
    )
    .unwrap();
    writeln!(out, "\\begin{{tikzpicture}}").unwrap();
    writeln!(out, "  \\useasboundingbox (0,0) rectangle (\\fw, -\\fh);").unwrap();

    for p in &layout.placements {
        let alt_note = p
            .alt_chosen
            .as_deref()
            .map(|a| format!("[{a}]"))
            .unwrap_or_default();

        // Inset the rect by half-gap to create visual spacing.
        let x = p.rect.x + hgw;
        let y = p.rect.y + hgh;
        let w = (p.rect.w - gap_w).max(0.01);
        let h = (p.rect.h - gap_h).max(0.01);

        // Content area: below the label gutter.
        let cy = y + label_h;
        let ch = (h - label_h).max(0.01);

        writeln!(out).unwrap();
        writeln!(
            out,
            "  % Panel {}{} ({}) — {:.1}×{:.1}mm, aspect {:.2} (target {:.2}), void {:.1}%",
            p.panel_id,
            alt_note,
            p.group_id,
            p.w_mm,
            p.h_mm,
            p.aspect_actual,
            p.aspect_target,
            p.void_frac * 100.0,
        )
        .unwrap();

        // Place the panel content centered within its content area.
        // \includesvg with both width and height constrains the SVG to fit
        // within the allocation (preserving aspect ratio), so no clip is needed.
        // anchor=center ensures content is centered when SVG aspect differs
        // from box aspect (e.g. TikZ panels with intrinsic aspect).
        let cx = x + w / 2.0;
        let ccy = cy + ch / 2.0;
        writeln!(
            out,
            "  \\node[anchor=center, inner sep=0pt] at ({cx:.4}\\fw, -{ccy:.4}\\fh) {{%",
        )
        .unwrap();
        writeln!(
            out,
            "    \\includesvg[width={w:.4}\\fw, height={ch:.4}\\fh]{{{figure}_{panel}}}}};",
            figure = layout.figure_name,
            panel = p.panel_id,
        )
        .unwrap();
    }

    // Inset panels — placed inside host panels' dead space.
    if !layout.inset_placements.is_empty() {
        writeln!(out).unwrap();
        writeln!(out, "  % Inset panels").unwrap();
        for ip in &layout.inset_placements {
            let x = ip.rect.x + hgw;
            let y = ip.rect.y + hgh;
            let w = (ip.rect.w - gap_w).max(0.01);
            let h = (ip.rect.h - gap_h).max(0.01);

            // Content area: below the label gutter.
            let cy = y + label_h;
            let ch = (h - label_h).max(0.01);

            writeln!(
                out,
                "\n  % Inset {panel} in {host} ({anchor:?}) — {w_mm:.1}×{h_mm:.1}mm, aspect {aa:.2} (target {at:.2}), void {vf:.1}%",
                panel = ip.panel_id,
                host = ip.host_id,
                anchor = ip.anchor,
                w_mm = ip.w_mm,
                h_mm = ip.h_mm,
                aa = ip.aspect_actual,
                at = ip.aspect_target,
                vf = ip.void_frac * 100.0,
            )
            .unwrap();
            let cx = x + w / 2.0;
            let ccy = cy + ch / 2.0;
            writeln!(
                out,
                "  \\node[anchor=center, inner sep=0pt] at ({cx:.4}\\fw, -{ccy:.4}\\fh) {{%",
            )
            .unwrap();
            writeln!(
                out,
                "    \\includesvg[width={w:.4}\\fw, height={ch:.4}\\fh]{{{figure}_{panel}}}}};",
                figure = layout.figure_name,
                panel = ip.panel_id,
            )
            .unwrap();
        }
    }

    writeln!(out).unwrap();

    // Panel labels — placed in the label gutter above each panel's content area.
    writeln!(out, "  % Panel labels").unwrap();
    for p in &layout.placements {
        let x = p.rect.x + hgw;
        let y = p.rect.y + hgh;
        if label_h > 0.0 {
            // Label sits in the reserved gutter, baseline-aligned to the
            // bottom of the gutter strip so it appears right above the content.
            writeln!(
                out,
                "  \\node[anchor=base west, font=\\large\\sffamily\\bfseries, inner sep=0pt] at ({x:.4}\\fw+1pt, -{y_bot:.4}\\fh+1pt) {{{letter}}};",
                y_bot = y + label_h,
                letter = p.panel_id,
            )
            .unwrap();
        } else {
            // No gutter — overlay label on panel content (legacy behavior).
            writeln!(
                out,
                "  \\node[anchor=north west, font=\\large\\sffamily\\bfseries, fill=white, fill opacity=0.8, text opacity=1, inner sep=1.5pt, rounded corners=1pt] at ({x:.4}\\fw+1pt, -{y:.4}\\fh-1pt) {{{letter}}};",
                letter = p.panel_id,
            )
            .unwrap();
        }
    }

    // Labels for inset panels.
    for ip in &layout.inset_placements {
        let x = ip.rect.x + hgw;
        let y = ip.rect.y + hgh;
        if label_h > 0.0 {
            writeln!(
                out,
                "  \\node[anchor=base west, font=\\large\\sffamily\\bfseries, inner sep=0pt] at ({x:.4}\\fw+1pt, -{y_bot:.4}\\fh+1pt) {{{letter}}};",
                y_bot = y + label_h,
                letter = ip.panel_id,
            )
            .unwrap();
        } else {
            writeln!(
                out,
                "  \\node[anchor=north west, font=\\large\\sffamily\\bfseries, fill=white, fill opacity=0.8, text opacity=1, inner sep=1.5pt, rounded corners=1pt] at ({x:.4}\\fw+1pt, -{y:.4}\\fh-1pt) {{{letter}}};",
                letter = ip.panel_id,
            )
            .unwrap();
        }
    }

    writeln!(out, "\\end{{tikzpicture}}").unwrap();
    out
}
